import mongoose from 'mongoose';

const appointmentSchema = new mongoose.Schema({
    student: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    date: {
        type: String, // Storing as YYYY-MM-DD for simpler exact matching
        required: true
    },
    timeSlot: {
        type: String,
        required: true,
        enum: [
            '9:00 AM - 10:00 AM',
            '10:00 AM - 11:00 AM',
            '11:00 AM - 12:00 PM',
            '1:00 PM - 2:00 PM',
            '2:00 PM - 3:00 PM',
            '3:00 PM - 4:00 PM',
            '4:00 PM - 5:00 PM'
        ]
    },
    reason: {
        type: String,
        required: true,
        trim: true
    },
    status: {
        type: String,
        enum: ['Pending', 'Approved', 'Rejected', 'Completed'],
        default: 'Pending'
    },
    adminNotes: {
        type: String,
        default: ''
    }
}, { timestamps: true });

// Prevent double booking at the schema level: A specific date and time slot should be unique
appointmentSchema.index({ date: 1, timeSlot: 1 }, { unique: true, partialFilterExpression: { status: { $in: ['Approved', 'Pending'] } } });

export { appointmentSchema };






const employeeSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    },
    role: {
        type: String,
        enum: ['admin', 'employee'],
        default: 'employee'
    }
}, { timestamps: true });